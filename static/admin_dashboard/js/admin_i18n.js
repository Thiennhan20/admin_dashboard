window.translateAdminFlash = function(rawText) {
    const text = (rawText || '').trim();
    if (!text) return rawText;
    if (window.ADMIN_FLASH_EXACT_EN[text]) {
        return window.ADMIN_FLASH_EXACT_EN[text];
    }
    const rules = [
        [/^Bạn đã đăng nhập với tài khoản (.+)$/, (_, u) => `Already signed in as ${u}`],
        [/^Chào mừng (.+?)! Đăng nhập thành công\.$/, (_, u) => `Welcome ${u}! Signed in successfully.`],
        [/^Chào mừng (.+?)! Xác thực 2FA thành công\.$/, (_, u) => `Welcome ${u}! 2FA verification successful.`],
        [/^Tên đăng nhập hoặc mật khẩu không đúng!(?: \(Còn (\d+) lần thử\))?$/, (_, n) => n ? `Incorrect username or password! (${n} attempts remaining)` : 'Incorrect username or password!'],
        [/^Mã OTP hoặc mã dự phòng không đúng! Còn (\d+) lần thử\.$/, (_, n) => `Incorrect OTP or backup code! ${n} attempts remaining.`],
        [/^Đã khởi tạo tài khoản quản trị: (.+)\.$/, (_, u) => `Created admin account: ${u}.`],
        [/^Đã xuất bản nhật ký (.+) và gửi thông báo tới người dùng!$/, (_, v) => `Changelog ${v} published and broadcast to users!`],
        [/^Đã gửi Email tới (\d+) người nhận!$/, (_, n) => `Email sent to ${n} recipient(s)!`],
        [/^Đã lưu Email \((\d+) người nhận\) nhưng máy chủ SMTP chưa được cấu hình\.$/, (_, n) => `Email saved (${n} recipients), but SMTP is not configured.`],
        [/^Gửi Email thất bại: (.+)$/, (_, err) => `Email failed: ${err}`],
        [/^Đã chuyển trạng thái báo cáo sang (.+)!$/, (_, st) => {
            const m = { 'đang xem xét': 'reviewing', 'đã xử lý': 'resolved', 'đã bỏ qua': 'dismissed' };
            return `Report marked as ${m[st] || st}!`;
        }],
        [/^Đã chạy (\d+) tác vụ đến hạn\.$/, (_, n) => `Executed ${n} due scheduled task(s).`],
        [/^Đã đăng xuất bắt buộc (\d+) thiết bị của người dùng!$/, (_, n) => `Forced logout on ${n} user device(s)!`],
        [/^Đã xóa người dùng và dọn sạch toàn bộ dữ liệu liên quan! \((\d+) bản ghi\)$/, (_, n) => `Deleted user and purged all related data! (${n} records)`],
        [/^Sao lưu thất bại: (.+)$/, (_, e) => `Backup failed: ${e}`],
        [/^File backup không hợp lệ: (.+)$/, (_, e) => `Invalid backup file: ${e}`],
        [/^Đã phân tích bản xem trước cho "(.+)"\. Kiểm tra bảng tác động bên dưới và nhấn Xác nhận khôi phục\.$/, (_, f) => `Analyzed restore preview for "${f}". Review the impact summary below and click Confirm Restore.`],
        [/^Khôi phục thành công \((.+)\): \+(\d+) bản ghi thêm mới, ~(\d+) bản ghi cập nhật trên (\d+) bảng dữ liệu\.$/, (_, mode, ins, upd, cols) => {
            const m = { 'cập nhật & bổ sung': 'upsert', 'chỉ thêm mới': 'insert only', 'thay thế toàn bộ': 'replace all' };
            return `Restore completed (${m[mode] || mode}): +${ins} inserted, ~${upd} updated across ${cols} collection(s).`;
        }],
        [/^Khôi phục thất bại: (.+)$/, (_, e) => `Restore failed: ${e}`],
        [/^Đã tạo thành công tài khoản ([^:]+): ([^ ]+) \(([^)]+)\)\.$/, (_, typ, user, role) => `Created ${typ} account: ${user} (${role}).`],
        [/^Đã xóa tài khoản admin: (.+)$/, (_, u) => `Deleted admin account: ${u}`],
        [/^Đã reset 2FA cho tài khoản (.+)\.$/, (_, u) => `Reset 2FA for account ${u}.`],
        [/^Đã dọn dẹp danh sách xem cho (\d+) người dùng!$/, (_, n) => `Cleaned watchlist for ${n} user(s)!`],
        [/^Không tìm thấy người dùng với ID: (.+)$/, (_, id) => `User not found with ID: ${id}`],
        [/^Lỗi: (.+)$/, (_, e) => `Error: ${e}`]
    ];
    for (const [pattern, formatter] of rules) {
        const match = text.match(pattern);
        if (match) return formatter(...match);
    }
    return rawText;
};
